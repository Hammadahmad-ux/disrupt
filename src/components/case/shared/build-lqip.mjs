// Builds lqip.json: a tiny blurred stand-in (20 px wide WebP, ~200 bytes, as a data URI) for every picture
// the case pages show, so a frame, still or poster is never an empty box while the real file loads.
// Run from web/ after the case media changes:  node src/components/case/shared/build-lqip.mjs
// Inputs (web/public/media/work/<slug>/): frames/NN-800.webp, rhythm/NN-800.webp, stills/NN-800.webp,
// poster.webp. Keys: "<slug>/frames/01", "<slug>/rhythm/01", "<slug>/stills/01", "<slug>/poster".
// Read on the server only (lqip.ts); each page gets just its own entries.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "../../../..");
const root = path.join(web, "public/media/work");
const out = path.join(here, "lqip.json");

const W = 20;
const tiny = async (file) => {
  const buf = await sharp(file).resize(W, null).webp({ quality: 55, smartSubsample: true }).toBuffer();
  return `data:image/webp;base64,${buf.toString("base64")}`;
};

const images = {};
for (const slug of fs.readdirSync(root).sort()) {
  const dir = path.join(root, slug);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const kind of ["frames", "rhythm", "stills"]) {
    const sub = path.join(dir, kind);
    if (!fs.existsSync(sub)) continue;
    for (const f of fs.readdirSync(sub).sort()) {
      const m = /^(\d\d)-800\.webp$/.exec(f);
      if (m) images[`${slug}/${kind}/${m[1]}`] = await tiny(path.join(sub, f));
    }
  }
  const poster = path.join(dir, "poster.webp");
  if (fs.existsSync(poster)) images[`${slug}/poster`] = await tiny(poster);
}

fs.writeFileSync(
  out,
  `${JSON.stringify({ _note: "Generated by build-lqip.mjs (same folder). Do not edit by hand.", images }, null, 1)}\n`,
);
const bytes = Object.values(images).reduce((s, v) => s + v.length, 0);
console.log(`${Object.keys(images).length} placeholders, ${(bytes / 1024).toFixed(1)} KB -> ${path.relative(web, out)}`);
